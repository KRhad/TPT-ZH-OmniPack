def load_descriptions(root: Path) -> dict[str, str]:
    data_path = root / "resources" / "element_descriptions_zh_CN.json"
    payload = json.loads(data_path.read_text(encoding="utf-8"))
    return payload["descriptions"]


def cpp_escape(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
    )


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    descriptions = load_descriptions(root)
    element_dir = root / "src" / "simulation" / "elements"
    files = {path.stem: path for path in element_dir.glob("*.cpp")}
    missing = sorted(set(files) - set(descriptions))
    extra = sorted(set(descriptions) - set(files))
    if missing or extra:
        raise SystemExit(f"description table mismatch: missing={missing}, extra={extra}")

    pattern = re.compile(r'(elem->Description\s*=\s*")((?:\\.|[^"\\])*)(";)')
    changed = 0
    for code, path in sorted(files.items()):
        source = path.read_text(encoding="utf-8")
        updated, count = pattern.subn(lambda m: m.group(1) + cpp_escape(descriptions[code]) + m.group(3), source, count=1)
        if count != 1:
            raise SystemExit(f"expected one description in {path}")
        if updated != source:
            path.write_text(updated, encoding="utf-8", newline="")
            changed += 1

    lengths = [len(value) for value in descriptions.values()]
    print(f"elements={len(descriptions)} changed={changed} min={min(lengths)} max={max(lengths)}")


if __name__ == "__main__":
    main()
